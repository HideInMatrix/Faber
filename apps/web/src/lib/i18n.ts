export function validLocale(value: unknown): value is AppLocale { return value === 'zh-CN' || value === 'en' }
export function readLocale(storage?: Pick<Storage, 'getItem'>): AppLocale {
  try { const value = storage?.getItem(LOCALE_STORAGE_KEY); return validLocale(value) ? value : 'zh-CN' }
  catch { return 'zh-CN' }
}
export function translate(message: string, locale: AppLocale, values: Readonly<Record<string, string | number>> = {}): string {
  const text = locale === 'en' && Object.hasOwn(englishMessages, message) ? englishMessages[message]! : message
  // A single pass preserves braces and Chinese in user-supplied parameters.
  return text.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key: string) => Object.hasOwn(values, key) ? String(values[key]) : match)
}
